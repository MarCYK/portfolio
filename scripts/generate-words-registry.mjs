import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const wordsDir = join(root, 'src', 'data', 'words');
const outFile = join(root, 'src', 'data', 'words-registry.generated.ts');

const files = readdirSync(wordsDir).filter(f => f.endsWith('.md'));

const entries = files.map(file => {
  const slug = file.replace(/\.md$/, '');
  const raw = readFileSync(join(wordsDir, file), 'utf8');
  return [slug, raw];
});

const json = JSON.stringify(entries, null, 2);
const body = `// AUTO-GENERATED by scripts/generate-words-registry.mjs — do not edit.
// Inlines src/data/words/*.md so the data layer has no runtime fs dependency.
export const wordsContent: Record<string, string> = Object.fromEntries(${json});
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, body, 'utf8');
console.log(`[words-registry] wrote ${entries.length} posts to ${outFile.replace(root + '/', '')}`);
